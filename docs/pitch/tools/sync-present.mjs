// Copies the presentation mode's beats from src/present/beats.js (on main, #330), with the numbers from
// public/present/plan.json filled in, and the line script-4min-en.md says over each beat, into beats.md, between the
// present-beats markers, so the captions in this folder match what ?present=1 shows. Reads the app's file; never
// writes it. Not part of the app build.
//
//   node docs/pitch/tools/sync-present.mjs [--beats <file>]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const APP = join(ROOT, '..', '..');
// --beats <file> reads another beats.js, for example one from an open PR: git show origin/<branch>:src/present/beats.js > /tmp/beats.js
const at = process.argv.indexOf('--beats');
const BEATS_FILE = at > 0 ? resolve(process.argv[at + 1]) : join(APP, 'src', 'present', 'beats.js');
const { BEATS, captionsOf } = await import(pathToFileURL(BEATS_FILE).href);
const { fill } = await import(pathToFileURL(join(APP, 'src', 'present', 'data.js')).href);
// Numbers in braces come from public/present/plan.json, as on screen. Live ones (the zone area) stay as written.
const plan = JSON.parse(readFileSync(join(APP, 'public', 'present', 'plan.json'), 'utf8'));
const num = (t) => fill(t, plan, 'en').replace(/\?/g, '(live)');

// What the presenter says over each beat: the row of script-4min-en.md with the same beat id.
const script = readFileSync(join(ROOT, 'script-4min-en.md'), 'utf8').split('\n')
  .filter((l) => /^\| \d+:\d\d \| [a-z]/.test(l))
  .map((l) => l.split('|').slice(1, -1).map((c) => c.trim()));
const said = Object.fromEntries(script.map(([time, id, who, text]) => [id, `${time} ${who}: ${text.replace(/\([^)]*\)\s*/g, '').trim()}`]));

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const caps = (b) => captionsOf(b).map((c) => `${c.en} / ${c.es}`).join('; then ');
const chips = (b) => (b.chips || []).map((c) => [c.big && num(c.big), c.text?.en && num(c.text.en)].filter(Boolean).join(' ') + (c.tag ? ` (${c.tag})` : '')).join('; ');

const rows = BEATS.map((b, i) => `| ${i + 1} | \`${b.id}\` | ${b.duration} | ${cell(caps(b))}${b.cta ? ` · button "${cell(b.cta.en)}"` : ''} | ${cell(chips(b))} | ${cell(b.source ? `${b.source.en} (${b.source.tag})` : '')} | ${cell(said[b.id] || (b.cta ? '(do not reach it: Right here hands over to the app)' : '(nothing said)'))} |`);
const known = new Set(BEATS.map((b) => b.id));
const missing = script.filter(([, id]) => !known.has(id)).map(([, id]) => `| - | \`${id}\` | | (not in this beats.js yet) | | | ${cell(said[id])} |`);
const block = [
  '<!-- present-beats:start (generated by tools/sync-present.mjs from src/present/beats.js; do not edit by hand) -->',
  '| # | Beat id | Seconds | Caption (EN / ES) | Chips (EN) | Source line | Presenter says (script-4min-en.md) |',
  '|---|---|---|---|---|---|---|',
  ...rows,
  ...missing,
  '<!-- present-beats:end -->',
].join('\n');

const file = join(ROOT, 'beats.md');
const md = readFileSync(file, 'utf8');
const re = /<!-- present-beats:start[\s\S]*?<!-- present-beats:end -->/;
if (!re.test(md)) throw new Error('beats.md has no present-beats markers');
writeFileSync(file, md.replace(re, block));
console.log(`synced ${BEATS.length} presentation beats from ${BEATS_FILE.split('/').pop()}${missing.length ? `; script beats not in it: ${missing.length}` : ''}`);
