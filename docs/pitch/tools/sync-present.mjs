// Copies the presentation mode's beats from src/present/beats.js (on main, #330), with the numbers from
// public/present/plan.json filled in, into beats.md, between the
// present-beats markers, so the captions in this folder match what ?present=1 shows. Reads the app's file; never
// writes it. Not part of the app build.
//
//   node docs/pitch/tools/sync-present.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const APP = join(ROOT, '..', '..');
const { BEATS, captionsOf } = await import(pathToFileURL(join(APP, 'src', 'present', 'beats.js')).href);
const { fill } = await import(pathToFileURL(join(APP, 'src', 'present', 'data.js')).href);
// Numbers in braces come from public/present/plan.json, as on screen. Live ones (the zone area) stay as written.
const plan = JSON.parse(readFileSync(join(APP, 'public', 'present', 'plan.json'), 'utf8'));
const num = (t) => fill(t, plan, 'en').replace(/\?/g, '(live)');

// Which line of script-5min-en.md each presentation beat sits under. Beats not listed are stepped past.
const CARRIES = {
  mars: '1a Jezero', jezero: '1a Jezero', cheyava: '1a Jezero', danger: '1b Thesis, 2 The limits', plan: '2 The limits',
  zone: '3 The walkback zone', radiation: '3 The walkback zone', storm: '5 The answer (second tab)',
  sources: '6 Measured or simulated, 7 Who (second tab)', live: 'Handover to demo cut A',
};

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const caps = (b) => captionsOf(b).map((c) => `${c.en} / ${c.es}`).join('; then ');
const chips = (b) => (b.chips || []).map((c) => [c.big && num(c.big), c.text?.en && num(c.text.en)].filter(Boolean).join(' ') + (c.tag ? ` (${c.tag})` : '')).join('; ');

const rows = BEATS.map((b, i) => `| ${i + 1} | \`${b.id}\` | ${b.duration} | ${cell(caps(b))}${b.cta ? ` · button "${cell(b.cta.en)}"` : ''} | ${cell(chips(b))} | ${cell(b.source ? `${b.source.en} (${b.source.tag})` : '')} | ${CARRIES[b.id] || ''} |`);
const block = [
  '<!-- present-beats:start (generated by tools/sync-present.mjs from src/present/beats.js; do not edit by hand) -->',
  '| # | Beat id | Seconds | Caption (EN / ES) | Chips (EN) | Source line | Under script line |',
  '|---|---|---|---|---|---|---|',
  ...rows,
  '<!-- present-beats:end -->',
].join('\n');

const file = join(ROOT, 'beats.md');
const md = readFileSync(file, 'utf8');
const re = /<!-- present-beats:start[\s\S]*?<!-- present-beats:end -->/;
if (!re.test(md)) throw new Error('beats.md has no present-beats markers');
writeFileSync(file, md.replace(re, block));
console.log(`synced ${BEATS.length} presentation beats from src/present/beats.js`);
